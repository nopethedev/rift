import "server-only";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../config";
import type { Settings } from "../settings";

export const lavalinkConfigDir = () => path.resolve(process.env.LAVALINK_CONFIG_DIR || path.join(env.dataDir, "lavalink"));

const q = (s: string) => JSON.stringify(s);

/**
 * application.yml for the bundled Lavalink service (read via SPRING_CONFIG_ADDITIONAL_LOCATION).
 * Rift's own bridge needs no plugin; plugins here add sources (e.g. a YouTube source plugin) to the node.
 */
export function renderLavalinkConfig(s: Pick<Settings, "musicLavalinkNodes" | "musicLavalinkPlugins">): string {
  const bundled = s.musicLavalinkNodes.find((n) => n.id === "bundled");
  const lines = ["# Generated by Rift (Admin → Music → Settings → Lavalink). Restart the lavalink container to apply.", "server:", "  port: 2333", "  address: 0.0.0.0", "lavalink:"];
  if (s.musicLavalinkPlugins.length) {
    lines.push("  plugins:");
    for (const p of s.musicLavalinkPlugins) {
      lines.push(`    - dependency: ${q(p.dependency)}`);
      if (p.repository) lines.push(`      repository: ${q(p.repository)}`);
    }
  }
  lines.push("  server:");
  if (bundled?.password) lines.push(`    password: ${q(bundled.password)}`);
  lines.push("    sources:", "      http: true", "      soundcloud: true", "      bandcamp: true", "      vimeo: false", "      twitch: false", "      local: false", "logging:", "  level:", "    root: INFO");
  return lines.join("\n") + "\n";
}

export async function writeLavalinkConfig(s: Pick<Settings, "musicLavalinkNodes" | "musicLavalinkPlugins">) {
  const dir = lavalinkConfigDir();
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, "application.yml");
  await writeFile(file, renderLavalinkConfig(s), { mode: 0o600 });
  return file;
}
