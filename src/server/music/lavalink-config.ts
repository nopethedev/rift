import "server-only";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../config";
import { defaultSettings, type Settings } from "../settings";

export const lavalinkConfigDir = () => path.resolve(process.env.LAVALINK_CONFIG_DIR || path.join(env.dataDir, "lavalink"));

const q = (s: string) => JSON.stringify(s);

/** Plugin versions Rift writes when the admin hasn't listed the plugin themselves (they can pin another version). */
export const PLUGINS = {
  youtube: "dev.lavalink.youtube:youtube-plugin:1.18.2",
  lavasrc: "com.github.topi314.lavasrc:lavasrc-plugin:4.8.3",
  lavalyrics: "com.github.topi314.lavalyrics:lavalyrics-plugin:1.1.0",
} as const;
const artifactOf = (dep: string) => dep.split(":").slice(0, 2).join(":");

type ConfigSettings = Pick<Settings, "musicLavalinkNodes" | "musicLavalinkPlugins"> & Partial<Pick<Settings, "musicLavalinkYoutube" | "musicLavalinkLyricsPlugins">>;

/** YouTube clients, in the order the plugin tries them. MUSIC only searches; the others also play. TV needs the sign-in. */
export const youtubeClients = (oauth: boolean) => (oauth ? ["MUSIC", "TV", "ANDROID_VR", "WEB", "WEBEMBEDDED", "TVHTML5_SIMPLY"] : ["MUSIC", "ANDROID_VR", "WEB", "WEBEMBEDDED", "TVHTML5_SIMPLY"]);

/**
 * application.yml for the bundled Lavalink service (read via SPRING_CONFIG_ADDITIONAL_LOCATION).
 * Rift's own bridge needs no plugin. Plugins add sources: YouTube (youtube-source; Lavalink's built-in YouTube source
 * no longer works and stays off) and lyrics (LavaLyrics, fed by LavaSrc's YouTube Music + LRCLIB lyrics, no accounts).
 */
export function renderLavalinkConfig(s: ConfigSettings): string {
  const bundled = s.musicLavalinkNodes.find((n) => n.id === "bundled");
  const yt = { ...defaultSettings().musicLavalinkYoutube, ...s.musicLavalinkYoutube };
  const lyrics = s.musicLavalinkLyricsPlugins ?? true;

  // The admin's own plugin list wins (e.g. a pinned version); Rift adds what's missing for the features turned on.
  const plugins = [...s.musicLavalinkPlugins];
  const listed = new Set(plugins.map((p) => artifactOf(p.dependency)));
  const want = (dep: string) => { if (!listed.has(artifactOf(dep))) { plugins.push({ dependency: dep, repository: "" }); listed.add(artifactOf(dep)); } };
  if (yt.enabled) want(PLUGINS.youtube);
  if (lyrics) { want(PLUGINS.lavasrc); want(PLUGINS.lavalyrics); }

  const lines = ["# Generated by Rift (Admin → Music → Settings → Lavalink). Restart the lavalink container to apply.", "server:", "  port: 2333", "  address: 0.0.0.0", "lavalink:"];
  if (plugins.length) {
    lines.push("  plugins:");
    for (const p of plugins) {
      lines.push(`    - dependency: ${q(p.dependency)}`);
      if (p.repository) lines.push(`      repository: ${q(p.repository)}`);
    }
  }
  lines.push("  server:");
  if (bundled?.password) lines.push(`    password: ${q(bundled.password)}`);
  // youtube: false is required by the youtube-source plugin (and the built-in source is broken anyway).
  lines.push("    sources:", "      youtube: false", "      http: true", "      soundcloud: true", "      bandcamp: true", "      vimeo: false", "      twitch: false", "      local: false");
  if (yt.enabled && yt.cipherUrl) lines.push("    timeouts:", "      connectTimeoutMs: 10000", "      connectionRequestTimeoutMs: 10000", "      socketTimeoutMs: 10000");

  if (yt.enabled || lyrics) lines.push("plugins:");
  if (yt.enabled) {
    lines.push("  youtube:", "    enabled: true", "    allowSearch: true", "    allowDirectVideoIds: true", "    allowDirectPlaylistIds: true", "    clients:");
    for (const c of youtubeClients(yt.oauth)) lines.push(`      - ${c}`);
    if (yt.oauth) {
      lines.push("    oauth:", "      enabled: true");
      if (yt.refreshToken) lines.push(`      refreshToken: ${q(yt.refreshToken)}`);
    }
    if (yt.poToken && yt.visitorData) lines.push("    pot:", `      token: ${q(yt.poToken)}`, `      visitorData: ${q(yt.visitorData)}`);
    if (yt.cipherUrl) {
      lines.push("    remoteCipher:", `      url: ${q(yt.cipherUrl)}`);
      if (yt.cipherPassword) lines.push(`      password: ${q(yt.cipherPassword)}`);
      lines.push(`      userAgent: "rift-music"`);
    }
  }
  if (lyrics) {
    // LavaSrc only for its lyrics here: every search/playback source of it stays off.
    lines.push("  lavasrc:", "    sources:", "      spotify: false", "      applemusic: false", "      deezer: false", "      yandexmusic: false", "      flowerytts: false", "      youtube: false", "      vkmusic: false", "      tidal: false", "      qobuz: false", "      ytdlp: false");
    lines.push("    lyrics-sources:", "      spotify: false", "      deezer: false", "      youtube: true", "      yandexmusic: false", "      vkmusic: false", "      lrcLib: true");
    lines.push("    youtube:", '      countryCode: "US"', '      language: "en"');
    // Time-synced LRCLIB first, then YouTube Music (often plain text).
    lines.push("  lavalyrics:", "    sources:", "      - lrclib", "      - youtube");
  }
  lines.push("logging:", "  level:", "    root: INFO", "    lavalink: INFO");
  // The sign-in prints its device code (and then the refresh token) through this logger.
  if (yt.enabled && yt.oauth) lines.push("    dev.lavalink.youtube.http.YoutubeOauth2Handler: INFO");
  return lines.join("\n") + "\n";
}

export async function writeLavalinkConfig(s: ConfigSettings) {
  const dir = lavalinkConfigDir();
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, "application.yml");
  await writeFile(file, renderLavalinkConfig(s), { mode: 0o600 });
  return file;
}
